% Show the radio journal of the one-device startDemo window; no new computation.
assert(exist('meetingApp','var')==1 && isstruct(meetingApp) && ...
    isfield(meetingApp,'Figure') && isvalid(meetingApp.Figure), ...
    'Keep the startDemo window open before showing its log.');
meetingLogSource=findall(meetingApp.Figure,'Tag','radioEventLog');
assert(isscalar(meetingLogSource),'The radio event journal was not found.');
meetingLogFigure=uifigure('Name','Радиособытия — завершённый пример с одним устройством', ...
    'Position',[100 100 1050 700]);
meetingLogGrid=uigridlayout(meetingLogFigure,[1 1]);
uitextarea(meetingLogGrid,'Value',meetingLogSource.Value, ...
    'Editable','off','FontSize',14,'WordWrap','on');
