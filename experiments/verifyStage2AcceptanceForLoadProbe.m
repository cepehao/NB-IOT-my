function acceptance=verifyStage2AcceptanceForLoadProbe(path,root,calibrationFile,registrySnapshotFile)
%VERIFYSTAGE2ACCEPTANCEFORLOADPROBE Validate Stage 2 evidence before new load work.
if nargin<2||isempty(root), root=fileparts(fileparts(mfilename('fullpath'))); end
if nargin<3||isempty(calibrationFile)
    calibrationFile=fullfile(root,'results','nprach-calibration.mat');
end
if nargin<4||isempty(registrySnapshotFile)
    registrySnapshotFile=fullfile(root,'experiments','realizationRegistry.json');
end
addpath(fullfile(root,'verification','completion','stage-2'));
if ~isfile(path)
    error('nbiot:experiments:PilotGate', ...
        'Stage 2 requires a technical acceptance.json before the load probe.');
end
try
    acceptance=jsondecode(fileread(path));
catch exception
    error('nbiot:experiments:PilotGate','Cannot decode Stage 2 acceptance: %s',exception.message);
end
required={'schemaVersion','status','humanReviewed','technicalReview', ...
    'physicalReport','physicalReportSha256','targetedLog','targetedLogSha256', ...
    'artifactSourceHashes','registrySha256','sourceManifestSha256', ...
    'calibrationSha256','receiverRevision','acceptanceLogicSha256', ...
    'artifactComparatorSha256'};
missing=required(~isfield(acceptance,required));
if ~isempty(missing)||~isequal(acceptance.schemaVersion,2)|| ...
        ~strcmp(char(string(acceptance.status)),'accepted-for-stage-3')|| ...
        ~islogical(acceptance.humanReviewed)||~isscalar(acceptance.humanReviewed)|| ...
        acceptance.humanReviewed||~isstruct(acceptance.technicalReview)|| ...
        ~isfield(acceptance.technicalReview,'reviewer')|| ...
        isempty(strtrim(char(string(acceptance.technicalReview.reviewer))))|| ...
        ~isfield(acceptance.technicalReview,'notes')|| ...
        isempty(strtrim(char(string(acceptance.technicalReview.notes))))
    error('nbiot:experiments:PilotGate','Stage 2 technical acceptance record is incomplete.');
end
physical=fullfile(root,strrep(char(string(acceptance.physicalReport)),'/',filesep));
targeted=fullfile(root,strrep(char(string(acceptance.targetedLog)),'/',filesep));
if ~isfile(physical)||~isfile(targeted)|| ...
        ~strcmp(fileHash(physical),char(string(acceptance.physicalReportSha256)))|| ...
        ~strcmp(fileHash(targeted),char(string(acceptance.targetedLogSha256)))
    error('nbiot:experiments:PilotGate','Stage 2 evidence is missing or changed after acceptance.');
end
saved=load(physical,'report');
if ~isfield(saved,'report')
    error('nbiot:experiments:PilotGate','Stage 2 physical report is missing its report variable.');
end
currentArtifacts=stage2ArtifactHashes(root);
currentManifest=optimizationSourceManifest(root);
calibrationPath=fullfile(root,'results','nprach-calibration.mat');
if ~isfield(saved.report,'artifactSourceHashes')||~isfield(saved.report,'registrySha256')|| ...
        ~isfield(saved.report,'sourceManifest')||~isfield(saved.report.sourceManifest,'sha256')|| ...
        ~isfield(saved.report,'calibrationSha256')|| ...
        ~stage2PhysicalArtifactsMatch(saved.report.artifactSourceHashes,acceptance.artifactSourceHashes)|| ...
        ~stage2PhysicalArtifactsMatch(saved.report.artifactSourceHashes,currentArtifacts)|| ...
        ~strcmp(saved.report.sourceManifest.sha256,char(string(acceptance.sourceManifestSha256)))|| ...
        ~strcmp(currentManifest.sha256,char(string(acceptance.sourceManifestSha256)))|| ...
        ~strcmp(fileHash(calibrationPath),char(string(acceptance.calibrationSha256)))|| ...
        ~strcmp(fileHash(calibrationFile),char(string(acceptance.calibrationSha256)))|| ...
        ~strcmp(saved.report.calibrationSha256,char(string(acceptance.calibrationSha256)))|| ...
        ~strcmp(fileHash(registrySnapshotFile),char(string(acceptance.registrySha256)))|| ...
        ~strcmp(saved.report.registrySha256,char(string(acceptance.registrySha256)))|| ...
        ~strcmp(nbiot.phy.nprach.receiverRevision(),char(string(acceptance.receiverRevision)))|| ...
        ~strcmp(fileHash(which('acceptStage2Evidence')),char(string(acceptance.acceptanceLogicSha256)))|| ...
        ~strcmp(fileHash(which('stage2PhysicalArtifactsMatch')), ...
        char(string(acceptance.artifactComparatorSha256)) )
    error('nbiot:experiments:PilotGate', ...
        'Stage 2 source code, registry snapshot or calibration changed after acceptance.');
end
end

function hex=fileHash(path)
fid=fopen(path,'rb');
if fid<0, error('nbiot:experiments:Hash','Cannot read %s.',path); end
cleanup=onCleanup(@() fclose(fid)); %#ok<NASGU>
digest=java.security.MessageDigest.getInstance('SHA-256');
while true
    bytes=fread(fid,4*1024*1024,'*uint8');
    if isempty(bytes), break; end
    digest.update(typecast(bytes(:),'int8'));
end
hex=lower(reshape(dec2hex(typecast(digest.digest(),'uint8'),2).',1,[]));
end
