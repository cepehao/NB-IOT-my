function text=formatResultSummary(result)
%FORMATRESULTSUMMARY Format the saved result metrics for the GUI summary.
required={'status','config','kpiSummary'};
if ~isstruct(result)||~isscalar(result)||~all(isfield(result,required))|| ...
        ~isfield(result.config,'simulation')||~isfield(result.config.simulation,'numUE')|| ...
        ~isstruct(result.kpiSummary)||~isscalar(result.kpiSummary)
    error('nbiot:ui:ResultSummary','The simulation result does not match the summary schema.');
end
k=result.kpiSummary;
lines={sprintf('Итог: %s · устройств: %s',char(string(result.status)), ...
    integerText(result.config.simulation.numUE))};
lines{end+1}=sprintf('Пакеты: создано %s, доставлено %s, потеряно %s, незавершено %s', ...
    numberText(numberValue(k,'created'),'%.0f'), ...
    numberText(numberValue(k,'delivered'),'%.0f'), ...
    numberText(numberValue(k,'dropped'),'%.0f'), ...
    numberText(numberValue(k,'unfinished'),'%.0f'));
lines{end+1}='Завершение по горизонту наблюдения не гарантирует доставку всех сообщений.';
lines{end+1}='Для показателей без выборки тире означает «нет данных», а не нулевую задержку или ноль ошибок.';
lines{end+1}=sprintf(['RA: попыток %s, успешно %s, неуспешно %s, незавершено %s; ' ...
    'успех %s; в среднем %s попытки на пакет; максимум на пакет %s'], ...
    numberText(numberValue(k,'raStarted'),'%.0f'), ...
    numberText(numberValue(k,'raSuccess'),'%.0f'), ...
    numberText(numberValue(k,'raFailed'),'%.0f'), ...
    numberText(numberValue(k,'raUnfinished'),'%.0f'), ...
    percentText(numberValue(k,'raSuccessProbability')), ...
    numberText(numberValue(k,'meanRaAttempts')), ...
    numberText(numberValue(k,'maxRaAttemptsPerPacket'),'%.0f'));
lines{end+1}=sprintf('Вероятность столкновения: %s', ...
    percentText(numberValue(k,'collisionAttemptProbability')));
if isfield(result,'radioDiagnostics')
    lines=[lines radioDiagnosticLines(result.radioDiagnostics)]; %#ok<AGROW>
else
    lines{end+1}=sprintf(['NPRACH (старые счётчики): кандидатов %s; логических групп %s; ' ...
        'попыток с совпадением преамбулы %s; физическая диагностика отсутствует'], ...
        numberText(numberValue(k,'detectedCandidates'),'%.0f'), ...
        numberText(numberValue(k,'logicalCollisionGroups'),'%.0f'), ...
        numberText(numberValue(k,'collidingAttempts'),'%.0f'));
    lines{end+1}='Радиодиагностика: в этом результате нет данных';
end
lines=[lines serviceKpiLines(k) groupKpiLines(result)]; %#ok<AGROW>

harq=struct();
if isfield(k,'harq')&&isstruct(k.harq)&&isscalar(k.harq), harq=k.harq; end
lines{end+1}=sprintf('NPUSCH: передач %s, принято блоков %s, отказов %s', ...
    numberText(numberValue(harq,'transmissionsStarted'),'%.0f'), ...
    numberText(numberValue(harq,'blocksAccepted'),'%.0f'), ...
    numberText(numberValue(harq,'blocksFailed'),'%.0f'));
lines{end+1}=sprintf(['CRC Msg3: успешно %s, ошибок %s, BLER %s; ' ...
    'CRC Data: успешно %s, ошибок %s, BLER %s'], ...
    crcPassed(k,'msg3Decoded','msg3CrcFailures'), ...
    numberText(numberValue(k,'msg3CrcFailures')), ...
    percentText(numberValue(k,'msg3Bler')), ...
    crcPassed(k,'dataDecoded','dataCrcFailures'), ...
    numberText(numberValue(k,'dataCrcFailures')), ...
    percentText(numberValue(k,'dataBler')));
lines{end+1}=sprintf(['Доставка: успех %s, потери %s; скорость %s бит/с; ' ...
    'задержка средняя %s мс; P95 задержка: %s мс'], ...
    percentText(numberValue(k,'deliveryProbability')), ...
    percentText(numberValue(k,'dropProbability')), ...
    numberText(numberValue(k,'throughputBitsPerSecond')), ...
    numberText(1000*delaySeconds(k,'meanDelaySeconds','meanDelayTicks',result),'%.1f'), ...
    unavailableNumberText(1000*numberValue(k,'p95DelaySeconds'),'%.1f'));
lines{end+1}=sprintf('Занятость UL/DL/NPRACH: %s / %s / %s', ...
    percentText(numberValue(k,'ulOccupancy')), ...
    percentText(numberValue(k,'dlOccupancy')), ...
    percentText(numberValue(k,'nprachOccupancy')));
lines{end+1}=sprintf(['Очередь BS: средняя %s, максимум %s; ' ...
    'пакетов в очереди UE: среднее %s, максимум %s'], ...
    numberText(numberValue(k,'meanBsQueueLength'),'%.1f'), ...
    numberText(numberValue(k,'maxBsQueueLength'),'%.0f'), ...
    numberText(numberValue(k,'meanUeQueueLength'),'%.1f'), ...
    numberText(numberValue(k,'maxUeQueueLength'),'%.0f'));

method='Static';
if isfield(result.config,'policy')&&isfield(result.config.policy,'name')
    method=char(string(result.config.policy.name));
end
action=struct();
if isfield(result,'runtimeAction')&&isstruct(result.runtimeAction)&&isscalar(result.runtimeAction)
    action=result.runtimeAction;
elseif isfield(result.config,'policy')
    action=result.config.policy;
end
access=numberValue(action,'accessProbability');
raShare=numberValue(action,'raShare');
if isfinite(raShare), raDt=sprintf('%d/%d',round(100*raShare),round(100*(1-raShare)));
else, raDt='нет данных'; end
if ~strcmp(method,'Static')
    decisions=NaN; switches=NaN;
    if isfield(k,'controller')&&isstruct(k.controller)
        decisions=firstValue(k.controller,{'decisionCount','decisions'});
        switches=numberValue(k.controller,'configurationSwitches');
    end
    lines{end+1}=sprintf('%s: решений %s, переключений %s, итоговые P = %s, RA/DT = %s', ...
        method,numberText(decisions),numberText(switches),percentProbability(access),raDt);
else
    lines{end+1}=sprintf('Static: итоговые P = %s, RA/DT = %s',percentProbability(access),raDt);
end
text=strjoin(lines,newline);
end

function lines=serviceKpiLines(summary)
service=structField(summary,'service');
required={'definition','available','actualTick','demandUeCount', ...
    'outageUeCount','unfinishedUeCount','probability'};
if ~all(isfield(service,required))
    lines={'Service outage: no data'};
    return;
end
definition=char(string(service.definition));
if isempty(definition), definition='unknown'; end
availability='';
if islogical(service.available)&&isscalar(service.available)&&~service.available
    availability=' (partial)';
end
lines={sprintf(['Service outage (%s): H=%s ticks, %s/%s demand UE, ' ...
    'P=%s%s, unfinished UE=%s'], ...
    definition,numberText(service.actualTick,'%.0f'), ...
    numberText(service.outageUeCount,'%.0f'), ...
    numberText(service.demandUeCount,'%.0f'), ...
    percentText(numberValue(service,'probability')),availability, ...
    numberText(service.unfinishedUeCount,'%.0f'))};
end

function lines=groupKpiLines(result)
required={'groupDimension','groupValue','ueCount','demandUeCount', ...
    'outageUeCount','delivered','created','unfinished', ...
    'packetDeliveryProbability','serviceOutageProbability', ...
    'raSuccess','raStarted'};
if ~isfield(result,'groupKpi')||~istable(result.groupKpi)|| ...
        ~all(ismember(required,result.groupKpi.Properties.VariableNames))|| ...
        height(result.groupKpi)==0
    lines={'Group KPIs: no data'};
    return;
end
groups=result.groupKpi;
lines=cell(1,height(groups));
for k=1:height(groups)
    dimension=char(string(groups.groupDimension(k)));
    value=char(string(groups.groupValue(k)));
    lines{k}=sprintf(['Group %s=%s: UE %s, demand %s, service outage %s (%s), ' ...
        'packet delivery %s (%s), RA success %s'], ...
        dimension,value,numberText(groups.ueCount(k),'%.0f'), ...
        numberText(groups.demandUeCount(k),'%.0f'), ...
        countRatioText(groups.outageUeCount(k),groups.demandUeCount(k), ...
            groups.serviceOutageProbability(k)), ...
        percentText(groups.serviceOutageProbability(k)), ...
        countRatioText(groups.delivered(k),groups.created(k), ...
            groups.packetDeliveryProbability(k)), ...
        percentText(groups.packetDeliveryProbability(k)), ...
        countRatioText(groups.raSuccess(k),groups.raStarted(k),NaN));
end
end

function text=countRatioText(numerator,denominator,probability)
text=sprintf('%s/%s',numberText(numerator,'%.0f'), ...
    numberText(denominator,'%.0f'));
if isfinite(probability)
    text=sprintf('%s (%s)',text,percentText(probability));
end
end

function lines=radioDiagnosticLines(radio)
lines={};
if ~isstruct(radio)||~isscalar(radio)
    lines={'Радиодиагностика: в этом результате нет данных'};
    return;
end
if ~isfield(radio,'available')||~islogical(radio.available)||~isscalar(radio.available)
    lines={'Радиодиагностика: в этом результате нет данных'};
    return;
end
if ~radio.available
    lines{end+1}='Радиодиагностика NPRACH: нет завершённых окон';
else
    preamble=structField(radio,'preamble');
    collision=structField(radio,'collision');
    capture=structField(radio,'capture');
    lines{end+1}=sprintf(['NPRACH: кандидатов %s; пропуски %s; ' ...
        'ложные тревоги %s'], ...
        numberText(numberValue(preamble,'detectedCandidates'),'%.0f'), ...
        countRateText(preamble,'misses','transmittedKeys','missProbability'), ...
        countRateText(preamble,'falseAlarms','falseAlarmOpportunities', ...
            'falseAlarmProbability'));
    lines{end+1}=sprintf(['Столкновения NPRACH: логические группы %s (%s/%s попыток); ' ...
        'физические пары %s (%s/%s попыток); capture %s/%s (%s)'], ...
        numberText(numberValue(collision,'logicalGroups'),'%.0f'), ...
        numberText(numberValue(collision,'logicalAttempts'),'%.0f'), ...
        numberText(numberValue(collision,'attempts'),'%.0f'), ...
        numberText(numberValue(collision,'physicalOverlapPairs'),'%.0f'), ...
        numberText(numberValue(collision,'physicalAttempts'),'%.0f'), ...
        numberText(numberValue(collision,'attempts'),'%.0f'), ...
        numberText(numberValue(capture,'capturedPairs'),'%.0f'), ...
        numberText(numberValue(capture,'eligiblePairs'),'%.0f'), ...
        percentText(numberValue(capture,'probability')));
end
perAttempt=structArrayField(radio,'perAttempt');
nprachEstimates=structArrayField(radio,'receiverEstimates');
npuschEstimates=structArrayField(radio,'npuschReceiverEstimates');
validSinr=finiteFieldCount(perAttempt,'sinrDb');
lines{end+1}=sprintf('Приёмник: SINR %s/%s; оценки NPRACH %s, NPUSCH %s', ...
    numberText(validSinr,'%.0f'),numberText(numel(perAttempt),'%.0f'), ...
    estimateCountText(nprachEstimates),estimateCountText(npuschEstimates));
end

function text=countRateText(source,countName,denominatorName,rateName)
text=sprintf('%s/%s (%s)', ...
    numberText(numberValue(source,countName),'%.0f'), ...
    numberText(numberValue(source,denominatorName),'%.0f'), ...
    percentText(numberValue(source,rateName)));
end

function text=estimateCountText(rows)
text=sprintf('%s',numberText(numel(rows),'%.0f'));
end

function count=finiteFieldCount(rows,name)
count=0;
if isempty(rows)||~isfield(rows,name), return; end
values=[rows.(name)];
count=sum(isfinite(values));
end

function rows=structArrayField(source,name)
rows=struct([]);
if isstruct(source)&&isscalar(source)&&isfield(source,name)&&isstruct(source.(name))
    rows=source.(name);
end
end

function value=structField(source,name)
value=struct();
if isstruct(source)&&isscalar(source)&&isfield(source,name)&& ...
        isstruct(source.(name))&&isscalar(source.(name))
    value=source.(name);
end
end

function value=crcPassed(summary,decodedName,failedName)
decoded=numberValue(summary,decodedName); failed=numberValue(summary,failedName);
if isfinite(decoded)&&isfinite(failed), value=numberText(max(0,decoded-failed));
else, value='нет данных'; end
end

function value=delaySeconds(summary,secondsName,ticksName,result)
value=numberValue(summary,secondsName);
if ~isfinite(value)&&isfield(summary,ticksName)&&isfield(result.config,'simulation')&& ...
        isfield(result.config.simulation,'tickSeconds')
    value=numberValue(summary,ticksName)*numberValue(result.config.simulation,'tickSeconds');
end
end

function value=firstValue(source,names)
value=NaN;
for k=1:numel(names)
    if isfield(source,names{k}), value=numberValue(source,names{k}); return; end
end
end

function value=numberValue(source,name)
value=NaN;
if isstruct(source)&&isfield(source,name)&&isnumeric(source.(name))&& ...
        isscalar(source.(name))&&isreal(source.(name))
    value=double(source.(name));
end
end

function text=integerText(value)
text=numberText(value,'%.0f');
end

function text=numberText(value,format)
if nargin<2, format='%.3g'; end
if ~isnumeric(value)||~isscalar(value)||~isreal(value)||~isfinite(value)
    text='нет данных';
else
    text=sprintf(format,double(value));
end
end

function text=unavailableNumberText(value,format)
text=numberText(value,format);
if strcmp(text,'нет данных'), text='—'; end
end

function text=percentText(value)
if isfinite(value), text=sprintf('%.1f%%',100*value); else, text='—'; end
end

function text=percentProbability(value)
if isfinite(value), text=sprintf('%.2f',value); else, text='—'; end
end
