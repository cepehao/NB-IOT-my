function explanation=explainMetric(key)
%EXPLAINMETRIC Return a short Russian explanation for a displayed UI value.
explanation='Описание недоступно';
if ~(ischar(key)&&isrow(key))&&~(isstring(key)&&isscalar(key))
    return;
end
key=char(string(key));
switch key
    case 'UE'
        explanation='UE — пользовательское устройство в модели сети.';
    case 'IDLE'
        explanation='Устройство свободно и сейчас не передаёт данные.';
    case 'WAIT_RA'
        explanation='Устройство готовит попытку доступа к сети.';
    case 'WAIT_RAR'
        explanation='Устройство ждёт ответ станции на запрос доступа.';
    case 'WAIT_MSG4'
        explanation='Продолжается служебное завершение процедуры доступа.';
    case 'BACKOFF'
        explanation='Устройство ждёт перед повторной попыткой доступа.';
    case 'DATA'
        explanation='Устройство передаёт полезные данные.';
    case 'WAIT_RECEIPT'
        explanation='Устройство ждёт подтверждение доставки передаваемых данных.';
    case 'MSG4_ACK'
        explanation='Подтверждение служебной процедуры доступа, а не доставка сообщения.';
    case 'RECEIPT_ACK'
        explanation='Подтверждение доставки сообщения.';
    case {'crc_data','crc_msg3'}
        explanation=['CRC — проверка принятых битов на ошибки. Ноль ошибок означает, ' ...
            'что проверка не обнаружила ошибок; «без CRC» означает, что проверка не выполнялась, ' ...
            'а не ошибку передачи.'];
    case 'connection'
        explanation='Подключение — служебная процедура доступа к сети; само по себе оно не означает доставку сообщения.';
    case 'payload_delivery'
        explanation='Доставка полезной нагрузки засчитывается отдельно от служебного подключения.';
    case 'packet_segmentation'
        explanation='Одно сообщение может передаваться несколькими частями; число частей не равно числу сообщений.';
    case 'progress'
        explanation='Показывает модельное время из заданного горизонта; реальное время с запуска и фаза расчёта отображаются отдельно.';
    case 'completed_horizon'
        explanation='Завершённый горизонт — конец наблюдения, он не гарантирует доставку всех сообщений.';
    case 'integer_counts'
        explanation='ID и счётчики показываются целыми числами; дробная часть не является дополнительным устройством или пакетом.';
    case 'metric_availability'
        explanation='Для показателя без доступных наблюдений показывается «нет данных»; тире в итоговой сводке имеет тот же смысл и не означает нулевую задержку или ноль ошибок.';
    case 'created'
        explanation='Создано — новые сообщения, появившиеся в выбранном окне; ноль в окне не означает пустую сеть.';
    case 'delivered'
        explanation='Доставлено — сообщения, полезная нагрузка которых достигла успешного завершения.';
    case 'dropped'
        explanation='Потеряно — сообщения, явно отброшенные моделью; незавершённые к концу окна считаются отдельно.';
    case 'unfinished'
        explanation='Незавершено — сообщения, которые ещё не доставлены и не отброшены к концу наблюдения.';
    case 'ra_success'
        explanation='Успех RA относится к процедуре случайного доступа и не означает доставку полезных данных.';
    case 'throughput'
        explanation='Скорость доставки — доставленные биты за окно времени; это не паспортная скорость модема.';
    case 'delay'
        explanation='Задержка измеряется для доставленных сообщений; без такой выборки показывается «нет данных».';
    case {'data_bler','msg3_bler'}
        explanation='BLER — доля блоков с ошибкой CRC среди блоков, для которых выполнена проверка.';
    case 'ra_dt'
        explanation='RA/DT — доли ресурсов, выделенные случайному доступу и передаче данных.';
    case 'P'
        explanation='P — вероятность попытки доступа, применяемая настройкой Static/Adaptive.';
    case 'nprach_detection_zero'
        explanation='Станция проверила возможность доступа, но не обнаружила запрос; это не новое подключение и не ошибка.';
    case 'bs_queue'
        explanation='Очередь BS — число ожидающих сообщений на базовой станции.';
    case 'ue_queue'
        explanation='Очередь UE — число пакетов в очереди устройства.';
    case 'ue_nonempty_queues'
        explanation='Число устройств с непустой очередью UE — количество устройств, у каждого из которых есть хотя бы один пакет; это не общее число пакетов.';
    otherwise
        return;
end
end
