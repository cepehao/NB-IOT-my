function report=checkEnvironment(runRoundtrip)
% Run only on the target MATLAB PC. No waveform result is precomputed.
if nargin<1, runRoundtrip=false; end
root=fileparts(fileparts(mfilename('fullpath'))); addpath(fullfile(root,'src'));
names={'lteNPRACH','lteNPRACHInfo','lteNPRACHDetect','lteNPUSCH','lteNPUSCHIndices','lteNPUSCHDRS',...
    'lteNPUSCHDRSIndices','lteNULSCH','lteNULSCHDecode','lteNPUSCHDecode',...
    'lteSCFDMAModulate','lteSCFDMADemodulate','lteULChannelEstimateNPUSCH','lteULFrameOffsetNPUSCH',...
    'lteNPDCCH','lteNPDCCHDecode','lteNPDCCHIndices','lteDCIEncode','lteDCIDecode',...
    'lteNPDSCH','lteNPDSCHDecode','lteNPDSCHIndices','lteNDLSCH','lteNDLSCHDecode',...
    'lteNRS','lteNRSIndices','lteDLChannelEstimate','lteExtractResources',...
    'lteBCH','lteNPBCH','lteNPBCHIndices','lteNPSS','lteNPSSIndices','lteNSSS','lteNSSSIndices'};
paths=cellfun(@which,names,'UniformOutput',false);
report=struct('release',version('-release'),'matlabVersion',version,...
    'lteToolbox',ver('lte'),'functions',table(names(:),paths(:),'VariableNames',{'Name','Path'}),...
    'roundtripRequested',logical(runRoundtrip),'roundtripExecuted',false,'roundtrip',[]);
disp(report.functions); fprintf('MATLAB %s\n',report.release);
nbiot.phy.requireToolbox(names);
if runRoundtrip
    report.roundtrip=nbiot.phy.verifyRoundtrips(); report.roundtripExecuted=true;
end
end
