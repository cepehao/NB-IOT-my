classdef TestExternalStageDispatch < matlab.unittest.TestCase
    methods (Test)
        function launcherCanResolveRealDispatcherFromCleanMatlabPath(t)
            projectRoot=fileparts(fileparts(mfilename('fullpath')));
            runnerPath=fullfile(projectRoot,'verification','external', ...
                'runExternalStages.ps1');
            runnerSource=fileread(runnerPath);
            matlabCode=regexp(runnerSource, ...
                '(?m)^\$matlabCode\s*=\s*"([^"]*)"','tokens','once');
            t.assertNotEmpty(matlabCode, ...
                'The launcher must define the MATLAB invocation code.');
            pathTokens=regexp(matlabCode{1}, ...
                "addpath\('([^']+)'\)",'tokens');
            t.assertNotEmpty(pathTokens, ...
                'The launcher must add its project paths before dispatch.');

            fixtureRoot=tempname;
            packageProject=fullfile(fixtureRoot,'project');
            dispatcherFolder=fullfile(packageProject,'verification', ...
                'external');
            mkdir(dispatcherFolder);
            mkdir(fullfile(packageProject,'experiments'));
            copyfile(fullfile(projectRoot,'verification','external', ...
                'runExternalStage.m'), ...
                fullfile(dispatcherFolder,'runExternalStage.m'));

            originalFolder=pwd;
            originalPath=path;
            restoreFolder=onCleanup(@() cd(originalFolder)); %#ok<NASGU>
            restorePath=onCleanup(@() path(originalPath)); %#ok<NASGU>
            removeFixture=onCleanup(@() removeFolder(fixtureRoot)); %#ok<NASGU>
            restoredefaultpath;
            cd(packageProject);
            for k=1:numel(pathTokens)
                addpath(fullfile(packageProject,pathTokens{k}{1}));
            end
            clear runExternalStage
            resolved=which('runExternalStage');
            expected=fullfile(dispatcherFolder,'runExternalStage.m');
            t.verifyEqual(resolved,expected, ...
                'A clean MATLAB path must resolve the packaged real dispatcher before invocation.');
            fprintf('BOUNDED_TEST real-dispatcher-resolved=%d\n', ...
                strcmp(resolved,expected));
        end

        function portablePackageIncludesStageWorkflow(t)
            [options,root,cleanup]=fixture(); %#ok<ASGLU>
            expected={ ...
                'verification/external/runExternalStages.ps1', ...
                'verification/external/testExternalStages.ps1', ...
                'verification/external/external-stages.schema.json', ...
                'verification/external/runExternalStage.m', ...
                'verification/external/validateExternalComparisonMatrix.m', ...
                'verification/local/InvokeBoundedProcess.ps1', ...
                'verification/local/OwnedProcessJob.cs', ...
                'docs/external-runbook.md'};
            sourceContents={ ...
                '# PowerShell runner fixture', ...
                '# PowerShell runner test fixture', ...
                '{"title":"External stages fixture"}', ...
                '% MATLAB dispatcher fixture', ...
                '% Comparison matrix validator fixture', ...
                '# Bounded process supervisor fixture', ...
                '// Owned process job fixture', ...
                'External runbook fixture'};
            for k=1:numel(expected)
                writeText(fullfile(root,strrep(expected{k},'/',filesep)), ...
                    sourceContents{k});
            end

            manifest=prepareExternalRun(options);
            fprintf('BOUNDED_TEST_PACKAGE manifest-created=1\n');

            packagedPaths={manifest.codeFiles.path};
            assetChecks=false(1,numel(expected));
            for k=1:numel(expected)
                source=fullfile(root,strrep(expected{k},'/',filesep));
                packaged=fullfile(options.outputFolder,'project', ...
                    strrep(expected{k},'/',filesep));
                assetChecks(k)=any(strcmp(packagedPaths,expected{k}))&& ...
                    isfile(packaged)&&isequal(readBytes(packaged),readBytes(source));
            end
            statePath=fullfile(options.outputFolder,'stages.json');
            stateExists=isfile(statePath);
            runbookCopied=isfile(fullfile(options.outputFolder,'external-runbook.md'));
            state=jsondecode(fileread(statePath));
            namesMatch=isequal({state.stages.name}, ...
                {'validate','pilot','data','assemble','train','freeze', ...
                'evaluate','admit','compare','summarize'});
            firstDependenciesEmpty=isempty(state.stages(1).dependencies);
            dependenciesMatch=isequal(state.stages(2).dependencies,{'validate'});
            pilotDecisionMatch=strcmp(state.stages(2).requiredDecision, ...
                'professor-approval-for-5000-UE-load-pilot');
            pilotApprovalPathMatch=strcmp( ...
                state.stages(2).configuration.pilot5000ApprovalFile, ...
                'reviews/pilot-5000-approval.json');
            statusMatch=all(strcmp({state.stages.status},'not-started'));
            commandMatch=all(arrayfun(@(item) ...
                strcmp(item.command.executable,'matlab'),state.stages));
            inputPathsMatch=false;
            try
                inputPathsMatch=all(arrayfun(@(item) ...
                    strcmp(item.inputs.path,'manifest.json'),state.stages));
            catch
            end
            fprintf(['BOUNDED_TEST_PACKAGE assets=%d stageNames=%d emptyInitialDependencies=%d ' ...
                'ledger=%d ' ...
                'validateDependencies=%d pilotDecision=%d pilotApprovalPath=%d ' ...
                'allNotStarted=%d matlabCommands=%d manifestInputs=%d runbook=%d\n'], ...
                sum(assetChecks),namesMatch,firstDependenciesEmpty,stateExists, ...
                dependenciesMatch,pilotDecisionMatch,pilotApprovalPathMatch,statusMatch, ...
                commandMatch,inputPathsMatch,runbookCopied);
            t.verifyTrue(all(assetChecks), ...
                'Every external stage workflow source must be packaged byte-for-byte.');
            t.verifyTrue(stateExists&&runbookCopied, ...
                'The stage ledger and operator runbook must be packaged.');
            t.verifyTrue(namesMatch&&firstDependenciesEmpty&&dependenciesMatch&& ...
                pilotDecisionMatch&&pilotApprovalPathMatch&& ...
                statusMatch&&commandMatch&&inputPathsMatch, ...
                'The package must contain the ten-stage chain, pilot approval reference, initial states, fixed commands and manifest inputs.');
            fprintf('BOUNDED_TEST_CASE=portable-package-assertions-finished\n');
        end

        function stageWorkflowRequiresBoundedProcessSupervisor(t)
            [options,root,cleanup]=fixture(); %#ok<ASGLU>
            workflowSources={ ...
                'verification/external/runExternalStages.ps1', ...
                'verification/external/testExternalStages.ps1', ...
                'verification/external/external-stages.schema.json', ...
                'verification/external/runExternalStage.m', ...
                'verification/external/validateExternalComparisonMatrix.m', ...
                'docs/external-runbook.md'};
            sourceContents={ ...
                '# PowerShell runner fixture', ...
                '# PowerShell runner test fixture', ...
                '{"title":"External stages fixture"}', ...
                '% MATLAB dispatcher fixture', ...
                '% Comparison matrix validator fixture', ...
                'External runbook fixture'};
            for k=1:numel(workflowSources)
                writeText(fullfile(root,strrep(workflowSources{k},'/',filesep)), ...
                    sourceContents{k});
            end

            identifier='';
            try
                prepareExternalRun(options);
            catch exception
                identifier=exception.identifier;
            end
            blocked=strcmp(identifier,'nbiot:externalRun:StageWorkflow')&& ...
                ~isfolder(options.outputFolder);
            fprintf('BOUNDED_TEST_STAGE_PACKAGE missing-process-supervisor-blocked=%d\n',blocked);
            t.verifyTrue(blocked);

            writeText(fullfile(root,'verification','local', ...
                'InvokeBoundedProcess.ps1'),'# Bounded process supervisor fixture');
            identifier='';
            try
                prepareExternalRun(options);
            catch exception
                identifier=exception.identifier;
            end
            jobBlocked=strcmp(identifier,'nbiot:externalRun:StageWorkflow')&& ...
                ~isfolder(options.outputFolder);
            fprintf('BOUNDED_TEST_STAGE_PACKAGE missing-owned-process-job-blocked=%d\n', ...
                jobBlocked);
            t.verifyTrue(jobBlocked, ...
                'The process supervisor package must include its OwnedProcessJob source dependency.');
        end

    end
end

