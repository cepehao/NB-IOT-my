function writeText(path,value)
parent=fileparts(path);
if ~isfolder(parent), mkdir(parent); end
fid=fopen(path,'w','n','UTF-8');
assert(fid>=0,'Could not create stage package fixture file.');
cleanup=onCleanup(@() fclose(fid));
fwrite(fid,unicode2native(value,'UTF-8'),'uint8');
end

function bytes=readBytes(path)
fid=fopen(path,'r');
assert(fid>=0,'Could not read stage package fixture file.');
cleanup=onCleanup(@() fclose(fid));
bytes=fread(fid,inf,'*uint8');
end

function removeFolder(path)
if isfolder(path)
    try
        rmdir(path,'s');
        fprintf('BOUNDED_TEST_CLEANUP removed=1\n');
    catch exception
        fprintf('BOUNDED_TEST_CLEANUP removed=0 identifier=%s\n',exception.identifier);
        rethrow(exception);
    end
end
