classdef TestResultSummaryFormatting < matlab.unittest.TestCase
    methods (Test)
        function finalSummaryShowsMetricsAlreadySavedInTheResult(test)
            result=completedAdaptiveResult();

            text=nbiot.ui.formatResultSummary(result);

            test.verifyTrue(contains(text,'устройств: 3'));
            test.verifyTrue(contains(text,'Пакеты: создано 8, доставлено 5, потеряно 2, незавершено 1'));
            test.verifyTrue(contains(text,'RA: попыток 12, успешно 6, неуспешно 5, незавершено 1'));
            test.verifyTrue(contains(text,'Вероятность столкновения: 25.0%'));
            test.verifyTrue(contains(text,'максимум на пакет 3'));
            test.verifyTrue(contains(text, ...
                'NPRACH: кандидатов 4; пропуски 1/2 (50.0%); ложные тревоги 1/10 (10.0%)'));
            test.verifyTrue(contains(text, ...
                'Столкновения NPRACH: логические группы 2 (3/4 попыток); физические пары 1 (2/4 попыток); capture 1/2 (50.0%)'));
            test.verifyTrue(contains(text, ...
                'Приёмник: SINR 1/2; оценки NPRACH 1, NPUSCH 1'));
            test.verifyFalse(contains(text,'успешный доступ при совпадении'));
            test.verifyTrue(contains(text,'NPUSCH: передач 9, принято блоков 3, отказов 2'));
            test.verifyTrue(contains(text,'CRC Data: успешно 5, ошибок 3, BLER 37.5%'));
            test.verifyTrue(contains(text,'P95 задержка: 4.0 мс'));
            test.verifyTrue(contains(text,'Занятость UL/DL/NPRACH: 10.0% / 20.0% / 30.0%'));
            test.verifyTrue(contains(text,'Очередь BS: средняя 2.0, максимум 5'));
            test.verifyTrue(contains(text,'Adaptive-P: решений 3, переключений 1, итоговые P = 0.50'));
        end

        function missingMeasurementsAreShownAsUnavailable(test)
            result=completedAdaptiveResult();
            result.kpiSummary.p95DelaySeconds=NaN;
            result.kpiSummary.nprachOccupancy=NaN;

            text=nbiot.ui.formatResultSummary(result);

            test.verifyTrue(contains(text,'P95 задержка: —'));
            test.verifyTrue(contains(text,'10.0% / 20.0% / —'));
            test.verifyFalse(contains(text,'NaN'));
        end

        function legacyResultExplainsThatRadioDiagnosticsAreUnavailable(test)
            result=completedAdaptiveResult();
            result=rmfield(result,'radioDiagnostics');

            text=nbiot.ui.formatResultSummary(result);

            test.verifyTrue(contains(text,'Радиодиагностика: в этом результате нет данных'));
            test.verifyFalse(contains(text,'успешный доступ при совпадении'));
            test.verifyFalse(contains(text,'NaN'));
        end

        function serviceOutageAndGroupMetricsAreShownFromSavedResult(test)
            result=completedAdaptiveResult();
            result.actualTick=5000;
            result.kpiSummary.service=struct( ...
                'definition','service-outage-horizon-v1', ...
                'available',true,'actualTick',5000,'demandUeCount',2, ...
                'outageUeCount',1,'unfinishedUeCount',0,'probability',0.5);
            result.groupKpi=table(["indoor";"coverageClass"], ...
                ["indoor";"CE0"],[2;3],[2;3],[1;1],[3;5],[1;4],[1;1], ...
                [1;0],[1/3;0.8],[0.5;1/3],[3;4],[1;3],[1;1],[1;0], ...
                'VariableNames',{'groupDimension','groupValue','ueCount', ...
                'demandUeCount','outageUeCount','created','delivered', ...
                'dropped','unfinished','packetDeliveryProbability', ...
                'serviceOutageProbability','raStarted','raSuccess', ...
                'raFailure','raUnfinished'});

            text=nbiot.ui.formatResultSummary(result);

            test.verifyTrue(contains(text,'Service outage'));
            test.verifyTrue(contains(text,'service-outage-horizon-v1'));
            test.verifyTrue(contains(text,'5000 ticks'));
            test.verifyTrue(contains(text,'1/2'));
            test.verifyTrue(contains(text,'50.0%'));
            test.verifyTrue(contains(text,'Group indoor=indoor'));
            test.verifyTrue(contains(text,'packet delivery 1/3'));
            test.verifyFalse(contains(text,'radio outage'));
            test.verifyFalse(contains(text,'NaN'));
        end

        function legacyResultMarksServiceAndGroupMetricsUnavailable(test)
            result=completedAdaptiveResult();

            text=nbiot.ui.formatResultSummary(result);

            test.verifyTrue(contains(text,'Service outage: no data'));
            test.verifyTrue(contains(text,'Group KPIs: no data'));
        end
    end
end

