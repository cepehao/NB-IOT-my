classdef TestDisplayRefresh < matlab.unittest.TestCase
    methods (Test)
        function redrawsAtEach100MillisecondBoundary(t)
            t.verifyFalse(nbiot.ui.shouldRefreshDisplay(99,0,false));
            t.verifyTrue(nbiot.ui.shouldRefreshDisplay(100,0,false));
            t.verifyFalse(nbiot.ui.shouldRefreshDisplay(199,100,false));
            t.verifyTrue(nbiot.ui.shouldRefreshDisplay(200,100,false));
        end

        function redrawsWhenRunFinishesBeforeBoundary(t)
            t.verifyTrue(nbiot.ui.shouldRefreshDisplay(17,0,true));
        end

        function formatsLiveRadioSummaryWithCurrentTimeAndCounts(t)
            live=struct();
            live.asOfTick=120;
            live.status='available';
            live.summary=struct( ...
                'available',true, ...
                'actualTick',120, ...
                'lastEventTick',111, ...
                'preamble',struct( ...
                    'transmittedAttempts',5, ...
                    'transmittedKeys',4, ...
                    'detectedCandidates',3, ...
                    'detectedKeys',2, ...
                    'misses',2, ...
                    'falseAlarms',1, ...
                    'falseAlarmOpportunities',6), ...
                'collision',struct( ...
                    'logicalGroups',2, ...
                    'logicalAttempts',3, ...
                    'physicalOverlapPairs',7, ...
                    'physicalAttempts',5), ...
                'capture',struct( ...
                    'eligiblePairs',4, ...
                    'censoredPairs',2, ...
                    'equalPowerPairs',1, ...
                    'capturedPairs',1));
            live.perUe=struct( ...
                'ueId',7, ...
                'sinrAvailable',true, ...
                'sinrDb',-2.5, ...
                'sinrTick',117, ...
                'lastEventTick',118);

            lines=nbiot.ui.formatLiveRadioSummary(live,7,1e-3);
            t.verifyTrue(iscell(lines));
            displayText=strjoin(lines,' ');
            lowerText=lower(displayText);
            t.verifyTrue(contains(displayText,'текущий момент'));
            t.verifyTrue(contains(displayText,'0.120 с'));
            t.verifyTrue(contains(displayText,'последнее событие'));
            t.verifyTrue(contains(displayText,'0.111 с'));
            t.verifyTrue(contains(displayText,'Передано попыток: 5'));
            t.verifyTrue(contains(displayText,'Передано ключей: 4'));
            t.verifyTrue(contains(displayText,'Обнаружено кандидатов: 3'));
            t.verifyTrue(contains(displayText,'Совпало ключей: 2'));
            t.verifyTrue(contains(displayText,'Пропуски: 2'));
            t.verifyTrue(contains(displayText,'Ложные тревоги: 1/6'));
            t.verifyTrue(contains(lowerText,'возможностей'));
            t.verifyTrue(contains(lowerText,'последнее событие ue'));
            t.verifyTrue(contains(displayText,'0.118 с'));
            t.verifyTrue(contains(displayText,'Логические коллизии: 2'));
            t.verifyTrue(contains(displayText,'Физические перекрытия: 7'));
            t.verifyTrue(contains(displayText,'Захват: 1/4'));
            t.verifyTrue(contains(displayText,'цензурировано: 2'));
            t.verifyTrue(contains(displayText,'одинаковая мощность: 1'));
            t.verifyTrue(contains(displayText,'SINR'));
            t.verifyTrue(contains(displayText,'2.5'));
            t.verifyTrue(contains(displayText,'дБ'));
            t.verifyTrue(contains(displayText,'0.117 с'));
        end

        function formatsMissingSinrAsUnavailable(t)
            live=struct();
            live.asOfTick=120;
            live.status='available';
            live.summary=struct( ...
                'available',true, ...
                'actualTick',120, ...
                'lastEventTick',111, ...
                'preamble',struct( ...
                    'transmittedAttempts',5, ...
                    'transmittedKeys',4, ...
                    'detectedCandidates',3, ...
                    'detectedKeys',2, ...
                    'misses',2, ...
                    'falseAlarms',1, ...
                    'falseAlarmOpportunities',6), ...
                'collision',struct( ...
                    'logicalGroups',0, ...
                    'logicalAttempts',0, ...
                    'physicalOverlapPairs',0, ...
                    'physicalAttempts',0), ...
                'capture',struct( ...
                    'eligiblePairs',0, ...
                    'censoredPairs',0, ...
                    'equalPowerPairs',0, ...
                    'capturedPairs',0));
            live.perUe=struct( ...
                'ueId',7, ...
                'sinrAvailable',false, ...
                'sinrDb',NaN, ...
                'sinrTick',NaN, ...
                'lastEventTick',118);

            lines=nbiot.ui.formatLiveRadioSummary(live,7,1e-3);
            displayText=strjoin(lines,' ');
            lowerText=lower(displayText);
            t.verifyTrue(contains(displayText,'SINR'));
            t.verifyTrue(contains(lowerText,'недоступ')|| ...
                contains(lowerText,'неизвест')||contains(lowerText,'нет данных'));
            t.verifyFalse(contains(displayText,'0 дБ'));
            t.verifyFalse(contains(displayText,'0.0 дБ'));
        end
    end
end
