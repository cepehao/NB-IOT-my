root=fileparts(fileparts(fileparts(mfilename('fullpath'))));
cd(root); addpath(root); setupProject();
packageRelative='verification/external/variant2-local-snapshot-20261014-seed43';
packageFolder=fullfile(root,strrep(packageRelative,'/',filesep));
assert(~isfolder(packageFolder),'nbiot:task6:PackageExists','Chosen package output already exists.');
registryFile=fullfile(root,'experiments','realizationRegistry.json');
registryShaBefore=nbiot.ml.fileSha256(registryFile);
counts=[100;500;1000;2500];
caseMatrix=table(repmat("Static",4,1),counts,repmat(5000,4,1), ...
    repmat("burst",4,1),repmat(100,4,1), ...
    'VariableNames',{'method','numUE','durationTicks','trafficKind','burstDurationTicks'});
noAssignments=table(zeros(0,1),strings(0,1), ...
    'VariableNames',{'externalRealizationId','role'});
options=struct('projectRoot',root,'outputFolder',packageRelative, ...
    'calibrationFile','results/nprach-calibration.mat', ...
    'registryFile','experiments/realizationRegistry.json', ...
    'caseMatrix',caseMatrix,'idAssignments',noAssignments, ...
    'expectedCalibrationSha256',nbiot.ml.fileSha256(fullfile(root,'results','nprach-calibration.mat')));
manifest=prepareExternalRun(options);
manifestPath=fullfile(packageFolder,'manifest.json');
assert(isfile(manifestPath),'nbiot:task6:Package','Package manifest was not written.');
assert(~manifest.readyForExecution&&isempty(manifest.idAssignments), ...
    'nbiot:task6:Package','Local package must remain a draft with no external IDs.');
assert(strcmp(manifest.calibration.sha256,nbiot.ml.fileSha256(fullfile(root,'results','nprach-calibration.mat'))), ...
    'nbiot:task6:Calibration','Packaged calibration does not match the working copy.');
for k=1:numel(manifest.codeFiles)
    entry=manifest.codeFiles(k);
    packaged=fullfile(packageFolder,strrep(entry.packagePath,'/',filesep));
    assert(isfile(packaged),'nbiot:task6:Package','Missing packaged source %s.',entry.path);
    assert(strcmp(nbiot.ml.fileSha256(packaged),entry.packageSha256), ...
        'nbiot:task6:PackageHash','Packaged source hash mismatch: %s.',entry.path);
end
required={'verification/completion/stage-2/stage2PhysicalProgress.m', ...
    'verification/completion/stage-2/runStage2Physical.ps1', ...
    'verification/completion/stage-3/runVariant2.ps1'};
packagedPaths=string({manifest.codeFiles.path});
assert(all(ismember(string(required),packagedPaths)), ...
    'nbiot:task6:Package','An approved Stage 2/3 runner source is missing from the package.');
registryShaAfter=nbiot.ml.fileSha256(registryFile);
assert(strcmp(registryShaBefore,registryShaAfter), ...
    'nbiot:task6:Registry','Package build changed the realization registry.');
packageManifestSha=nbiot.ml.fileSha256(manifestPath);
report=struct('status','draft-needs-external-review','packageFolder',packageRelative, ...
    'packageManifestSha256',packageManifestSha,'codeManifestSha256',manifest.codeManifestSha256, ...
    'codeFileCount',numel(manifest.codeFiles),'calibrationSha256',manifest.calibration.sha256, ...
    'requiredSourcesIncluded',{required},'externalIdCount',numel(manifest.idAssignments), ...
    'readyForExecution',manifest.readyForExecution,'registrySha256Before',registryShaBefore, ...
    'registrySha256After',registryShaAfter,'builtAtUtc',char(datetime('now','TimeZone','UTC', ...
    'Format','yyyy-MM-dd''T''HH:mm:ss''Z''')));
reportPath=fullfile(root,'verification','external','variant2-local-snapshot-20261014-seed43-build-report.json');
fid=fopen(reportPath,'w','n','UTF-8'); assert(fid>=0,'nbiot:task6:Report','Cannot write package report.');
cleanup=onCleanup(@() fclose(fid));
fwrite(fid,unicode2native(jsonencode(report,'PrettyPrint',true),'UTF-8'),'uint8');
fprintf('TASK6_PACKAGE_READY folder=%s codeFiles=%d readyForExecution=%d\n', ...
    packageRelative,numel(manifest.codeFiles),manifest.readyForExecution);
fprintf('TASK6_PACKAGE_REPORT=%s\n',strrep(reportPath,[root filesep],''));
