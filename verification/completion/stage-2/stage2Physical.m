function report=stage2Physical(execution,dryRun,runOptions)
%STAGE2PHYSICAL Run or plan the fresh, bounded Stage 2 physical evidence set.
if nargin<1, execution=struct(); end
if nargin<2, dryRun=false; end
if nargin<3, runOptions=struct(); end
defaults=struct('outputFolder','','resume',false,'budgetLedgerFile','', ...
    'realizationSeed',42);
assert(isstruct(runOptions)&&isscalar(runOptions)&&...
    all(ismember(fieldnames(runOptions),fieldnames(defaults))),...
    'nbiot:stage2:RunOptions','Invalid Stage 2 output or resume options.');
names=fieldnames(runOptions);
for k=1:numel(names), defaults.(names{k})=runOptions.(names{k}); end
runOptions=defaults;
assert(isnumeric(runOptions.realizationSeed)&&isreal(runOptions.realizationSeed)&&...
    isscalar(runOptions.realizationSeed)&&isfinite(runOptions.realizationSeed)&&...
    runOptions.realizationSeed==fix(runOptions.realizationSeed)&&...
    runOptions.realizationSeed>=0&&runOptions.realizationSeed<=2^32-1,...
    'nbiot:stage2:Seed','realizationSeed must be an integer from 0 through 2^32-1.');
runOptions.realizationSeed=double(runOptions.realizationSeed);
assert(isscalar(runOptions.resume)&&(islogical(runOptions.resume)||ismember(runOptions.resume,[0 1])),...
    'nbiot:stage2:RunOptions','resume must be a scalar logical flag.');
runOptions.resume=logical(runOptions.resume);
assert(isscalar(dryRun)&&(islogical(dryRun)||ismember(dryRun,[0 1])), ...
    'nbiot:stage2:DryRun','dryRun must be a scalar logical flag.');
dryRun=logical(dryRun);

root=fileparts(fileparts(fileparts(fileparts(mfilename('fullpath')))));
originalDirectory=pwd;
directoryCleanup=onCleanup(@() cd(originalDirectory));
cd(root); addpath(root); addpath(fullfile(root,'experiments')); setupProject();
design=validateCollisionCapture(struct('designOnly',true, ...
    'realizationSeed',runOptions.realizationSeed));
conditions=design.conditions;
repeats=10; durationTicks=1500;
runReceiverChecks=true; runInterferenceReplay=true;
numCases=repeats*numel(conditions)+8*repeats*runReceiverChecks+2*runInterferenceReplay;
requiredMaxUE=max([conditions.numUE]);
budgetCfg=nbiot.config.defaultConfig();
budgetCfg.simulation.numUE=requiredMaxUE;
budget=nbiot.experiments.validateExecutionBudget(budgetCfg,execution,numCases);
execution=rmfield(budget,'numCases');

stamp=char(datetime('now','Format','yyyyMMdd-HHmmss-SSS'));
stageFolder=fullfile(root,'verification','completion','stage-2');
if runOptions.resume
    assert(~isempty(runOptions.outputFolder)&&isfolder(runOptions.outputFolder),...
        'nbiot:stage2:Output','Resume requires the original physical evidence folder.');
    outputFolder=char(runOptions.outputFolder);
else
    if isempty(runOptions.outputFolder)
        outputFolder=fullfile(stageFolder,['physical-' stamp]);
    else
        outputFolder=char(runOptions.outputFolder);
    end
end
if dryRun
    report=struct('dryRun',true,'conditions',conditions,'repeats',repeats, ...
        'durationTicks',durationTicks,'runReceiverChecks',runReceiverChecks, ...
        'runInterferenceReplay',runInterferenceReplay,'numCases',numCases, ...
        'requiredMaxUE',requiredMaxUE,'maxUE',budget.maxUE, ...
        'execution',execution,'outputFolder',outputFolder, ...
        'realizationSeed',runOptions.realizationSeed);
    fprintf(['STAGE2_PHYSICAL_DRY_RUN conditions=%d cases=%d requiredMaxUE=%d ' ...
        'profile=%s registryUnchanged=1 physicalRun=0\n'], ...
        numel(conditions),numCases,requiredMaxUE,budget.profile);
    return
end

assert(strcmp(version('-release'),'2025b'), ...
    'nbiot:stage2:Release','Stage 2 evidence must be collected with MATLAB R2025b.');
lte=ver('lte'); assert(~isempty(lte), ...
    'nbiot:stage2:Toolbox','LTE Toolbox is required for physical diagnostics.');
if ~runOptions.resume
    assert(~isfolder(outputFolder),'nbiot:stage2:Output', ...
        'The physical output folder already exists; do not overwrite evidence.');
end
logName=char(java.util.UUID.randomUUID());
logFile=fullfile(stageFolder,['physical-' stamp '-' logName(1:8) '.log']);
diary(logFile); diaryCleanup=onCleanup(@() diary('off'));
fprintf('STAGE2_PHYSICAL matlab=%s release=%s output=%s\n', ...
    version,version('-release'),outputFolder);
fprintf('LTE_TOOLBOX version=%s\n',lte.Version);
options=struct('repeats',repeats,'conditionIds',[conditions.id], ...
    'durationTicks',durationTicks,'outputFolder',outputFolder, ...
    'runReceiverChecks',runReceiverChecks, ...
    'runInterferenceReplay',runInterferenceReplay, ...
    'registryFile',fullfile(root,'experiments','realizationRegistry.json'), ...
    'execution',execution,'resume',runOptions.resume, ...
    'budgetLedgerFile',runOptions.budgetLedgerFile, ...
    'realizationSeed',runOptions.realizationSeed);
report=validateCollisionCapture(options);
report.realizationSeed=runOptions.realizationSeed;
assert(isfield(report,'registrySha256')&&~isempty(report.registrySha256), ...
    'nbiot:stage2:Registry','Stage 2 run did not finalize its realization registry.');
save(fullfile(outputFolder,'stage2-report.mat'),'report','-v7');
save(fullfile(outputFolder,'report.mat'),'report','-v7');
fprintf('STAGE2_PHYSICAL_STATUS status=%s conditions=%d trials=%d receiverChecks=%d pendingCases=%d output=%s\n', ...
    report.status,numel(report.conditions),height(report.trials), ...
    height(report.receiverChecks),numel(report.pendingCases),outputFolder);
end
