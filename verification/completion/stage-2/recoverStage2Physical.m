function report=recoverStage2Physical(sourceFolder,replayFolder)
%RECOVERSTAGE2PHYSICAL Rebuild acceptance data after a post-sampling failure.
root=fileparts(fileparts(fileparts(fileparts(mfilename('fullpath')))));
addpath(root); setupProject(); addpath(fullfile(root,'experiments'));
sourceFolder=resolveFolder(root,sourceFolder); replayFolder=resolveFolder(root,replayFolder);
assert(~isfile(fullfile(sourceFolder,'stage2-report.mat'))&&...
    ~isfile(fullfile(sourceFolder,'report.mat')),...
    'nbiot:stage2:Recovery','Recovery output already exists; use a fresh source folder.');
physicalLog=[sourceFolder '.log'];
assert(isfile(physicalLog),'nbiot:stage2:Recovery','Original physical run log is missing.');
originalLog=fileread(physicalLog);
rawRunReport=fullfile(sourceFolder,'physical-run-report.mat');
assert(isfile(rawRunReport),'nbiot:stage2:Recovery',...
    'physical-run-report.mat is required; legacy physical evidence has no verifiable source provenance.');
manifestPath=fullfile(sourceFolder,'revalidation-manifest.json');
assert(isfile(manifestPath)&&contains(originalLog,'STAGE2_REVALIDATION_DONE'),...
    'nbiot:stage2:Recovery','Paired revalidation manifest or completion log is missing.');
savedRun=load(rawRunReport,'report');
assert(isfield(savedRun,'report')&&isfield(savedRun.report,'trials')&&...
    height(savedRun.report.trials)==150&&isfield(savedRun.report,'receiverChecks')&&...
    height(savedRun.report.receiverChecks)==80,...
    'nbiot:stage2:Recovery','Paired revalidation report is incomplete.');
revalidationManifest=jsondecode(fileread(manifestPath));
calibrationPath=fullfile(root,'results','nprach-calibration.mat');
officialRegistry=fullfile(root,'experiments','realizationRegistry.json');
validateStage2RevalidationProvenance(savedRun.report,revalidationManifest,...
    fileHash(calibrationPath),fileHash(officialRegistry));
currentArtifacts=stage2ArtifactHashes(root); currentManifest=optimizationSourceManifest(root);
assert(isequal(savedRun.report.artifactSourceHashes,currentArtifacts)&&...
    strcmp(savedRun.report.sourceManifest.sha256,currentManifest.sha256),...
    'nbiot:stage2:Recovery','Paired collision/receiver data were generated by a different source revision.');
assert(strcmp(savedRun.report.matlabRelease,'2025b')&&~isempty(savedRun.report.lteVersion),...
    'nbiot:stage2:Recovery','Physical revalidation must identify MATLAB R2025b and LTE Toolbox.');
assert(strcmp(char(java.io.File(savedRun.report.options.calibrationFile).getCanonicalPath()),...
    char(java.io.File(calibrationPath).getCanonicalPath())),...
    'nbiot:stage2:Recovery','Physical run used an unexpected calibration path.');
revalidation=savedRun.report.revalidation;
beforeRegistryPath=resolveEvidencePath(root,revalidation.officialRegistryBeforeSnapshot);
afterRegistryPath=resolveEvidencePath(root,revalidation.officialRegistryAfterSnapshot);
temporaryRegistry=resolveEvidencePath(root,revalidation.temporaryRegistry);
assert(isfile(temporaryRegistry)&&strcmp(fileHash(temporaryRegistry),...
    revalidation.temporaryRegistrySha256),...
    'nbiot:stage2:Recovery','Temporary registry changed after physical sampling.');
assert(isfile(beforeRegistryPath)&&isfile(afterRegistryPath)&&...
    strcmp(fileHash(beforeRegistryPath),revalidation.officialRegistrySha256BeforeRun)&&...
    strcmp(fileHash(afterRegistryPath),revalidation.officialRegistrySha256AfterRun),...
    'nbiot:stage2:Recovery','Archived official registry snapshots do not match their recorded hashes.');
beforeRegistry=jsondecode(fileread(beforeRegistryPath));
afterRegistry=jsondecode(fileread(afterRegistryPath));
collisionIds=sort(unique(double(savedRun.report.trials.realizationId(:).')));
receiverIds=sort(unique(double(savedRun.report.receiverChecks.id(:).')));
assert(isequal(collisionIds,sort(double(revalidation.collisionIds(:).')))&&...
    isequal(receiverIds,sort(double(revalidation.freshReceiverIds(:).'))),...
    'nbiot:stage2:Recovery','Physical run IDs do not match the paired revalidation manifest.');
requireRegistryAssignment(beforeRegistry,'stage-2-collision-diagnostics',collisionIds,'failed');
requireRegistryAssignment(afterRegistry,'stage-2-collision-diagnostics',collisionIds,'failed');
requireRegistryAssignment(beforeRegistry,'stage-2-receiver-diagnostics',receiverIds,'planned');
requireRegistryAssignment(afterRegistry,'stage-2-receiver-diagnostics',receiverIds,'completed');
assert(numel(receiverIds)==10&&isempty(intersect(collisionIds,receiverIds))&&...
    isempty(intersect(receiverIds,double(revalidation.previousReceiverIds(:).'))),...
    'nbiot:stage2:Recovery','Receiver IDs must be fresh and disjoint from collision and prior receiver IDs.');
design=validateCollisionCapture(struct('designOnly',true)); conditions=design.conditions;
files=dir(fullfile(sourceFolder,'condition-*.mat'));
assert(numel(files)==150,'nbiot:stage2:Recovery','Expected 150 saved collision trials.');
rowNames={'conditionId','group','realizationId','numUE','deltaDb','firstCandidates',...
    'logicalColliders','firstSuccess','raSuccess','delivered','firstStrongSuccess',...
    'firstWeakSuccess','firstAllSuccess','firstAnySuccess','firstMiss','firstFalseDetection',...
    'firstUnresolvedCollision','chainValidated','chainCount','dataCrcFailures','harqRetries'};
rows=cell(0,numel(rowNames)); idLists=cell(numel(conditions),1); seen=[];
for k=1:numel(files)
    tokens=regexp(files(k).name,'^condition-(\d+)-id-(\d+)\.mat$','tokens','once');
    assert(~isempty(tokens),'nbiot:stage2:Recovery','Unexpected condition evidence filename.');
    conditionId=str2double(tokens{1}); realizationId=str2double(tokens{2});
    ci=find([conditions.id]==conditionId,1);
    assert(~isempty(ci),'nbiot:stage2:Recovery','Saved trial refers to an unknown condition.');
    path=fullfile(files(k).folder,files(k).name); saved=load(path,'evidence');
    assert(isfield(saved,'evidence')&&all(isfield(saved.evidence,{'condition','cfg','result','trace'})),...
        'nbiot:stage2:Recovery','Saved condition file lacks required physical evidence.');
    e=saved.evidence;
    assert(isequal(e.condition,conditions(ci))&&...
        e.cfg.simulation.realizationId==realizationId&&...
        e.cfg.simulation.durationTicks==1500&&strcmp(e.result.status,'completed'),...
        'nbiot:stage2:Recovery','Saved trial metadata does not match its condition and filename.');
    rows(end+1,:)=nbiot.experiments.analyzeCollisionTrial(...
        e.condition,e.cfg,e.result,e.trace); %#ok<AGROW>
    idLists{ci}(end+1)=realizationId;
    seen(end+1,:)=[conditionId realizationId]; %#ok<AGROW>
end
assert(size(unique(seen,'rows'),1)==150,'nbiot:stage2:Recovery','Duplicate condition/ID evidence found.');
for ci=1:numel(conditions)
    idLists{ci}=sort(idLists{ci});
    assert(numel(idLists{ci})==10&&numel(unique(idLists{ci}))==10,...
        'nbiot:stage2:Recovery','Each condition must contain ten unique realization IDs.');
end
for ci=2:6
    assert(isequal(idLists{ci},idLists{1}),'nbiot:stage2:Recovery',...
        'Same-preamble near-far conditions do not share paired external IDs.');
end
for ci=8:12
    assert(isequal(idLists{ci},idLists{7}),'nbiot:stage2:Recovery',...
        'Different-preamble near-far conditions do not share paired external IDs.');
end

receiverPath=fullfile(sourceFolder,'receiver-checks.mat');
assert(isfile(receiverPath)&&isfile(fullfile(sourceFolder,'receiver-checks.csv')),...
    'nbiot:stage2:Recovery','Saved receiver-check evidence is incomplete.');
receiver=load(receiverPath,'checks');
assert(isfield(receiver,'checks'),'nbiot:stage2:Recovery','Receiver-check table is missing.');
nbiot.experiments.validateStage2ReceiverChecks(receiver.checks);
collisionIds=unique([idLists{:}]); receiverIds=sort(unique(double(receiver.checks.id(:).')));
assert(numel(receiverIds)==10&&isempty(intersect(collisionIds,receiverIds)),...
    'nbiot:stage2:Recovery','Receiver and collision IDs must be ten distinct, disjoint assignments.');

replayPath=fullfile(replayFolder,'report.mat');
assert(isfile(replayPath),'nbiot:stage2:Recovery','Corrected replay report is missing.');
replaySaved=load(replayPath,'report');
assert(isfield(replaySaved,'report')&&height(replaySaved.report.interferenceReplay)==8,...
    'nbiot:stage2:Recovery','Corrected replay report is incomplete.');
replayReport=replaySaved.report;
assert(isequal(replayReport.artifactSourceHashes,currentArtifacts)&&...
    strcmp(replayReport.sourceManifest.sha256,currentManifest.sha256),...
    'nbiot:stage2:Recovery','Corrected replay was generated by a different source revision.');
verifyReplay(replayReport.interferenceReplay);

trials=cell2table(rows,'VariableNames',rowNames); summaries={};
for ci=1:numel(conditions)
    selected=trials(trials.conditionId==conditions(ci).id,:);
    metrics={'firstStrongSuccess','firstWeakSuccess','firstAllSuccess','firstAnySuccess',...
        'firstMiss','firstFalseDetection','firstUnresolvedCollision'};
    if conditions(ci).deltaDb==0
        metrics=metrics(~ismember(metrics,{'firstStrongSuccess','firstWeakSuccess'}));
    end
    for mi=1:numel(metrics)
        count=sum(selected.(metrics{mi})); interval=binomialInterval(count,height(selected));
        summaries(end+1,:)={conditions(ci).id,conditions(ci).name,metrics{mi},height(selected),...
            count,count/height(selected),interval(1),interval(2)}; %#ok<AGROW>
    end
end

recoveryNote=['After the detector fix, all 150 collision trials were rerun as a paired '...
    'revalidation on the same unique realization IDs as the failed earlier run. These '...
    'paired repeats verify the new receiver revision but do not add a second independent '...
    'collision sample. The 80 receiver checks use ten fresh, disjoint IDs per condition. '...
    'The revised receiver has a fresh accepted calibration; the equal-power and 40 dB '...
    'CRC replay was rerun under the same source revision. Runtime is recorded from the '...
    'completed paired batch.'];
notePath=fullfile(sourceFolder,'recovery-notes.md');
fid=fopen(notePath,'w','n','UTF-8');
assert(fid>=0,'nbiot:stage2:Recovery','Could not write recovery notes.');
fwrite(fid,unicode2native(recoveryNote,'UTF-8'),'uint8'); fclose(fid);
evidenceFiles=[string({files.folder})+filesep+string({files.name}),...
    string(receiverPath),string(fullfile(sourceFolder,'receiver-checks.csv')),...
    string(physicalLog),...
    string(replayPath),string(fullfile(replayFolder,'interference-replay-00.mat')),...
    string(fullfile(replayFolder,'interference-replay-40.mat')),...
    string(fullfile(replayFolder,'interference-replay.csv')),...
    string(fullfile(root,'verification','completion','stage-2','recoverStage2Physical.m')),...
    string(fullfile(root,'src','+nbiot','+experiments','reconcileFailedRealizationUse.m')),...
    string(fullfile(root,'src','+nbiot','+experiments','analyzeCollisionTrial.m')),...
    string(fullfile(root,'results','nprach-calibration.mat')),...
    string(fullfile(root,'verification','completion','stage-2','calibration-r2025b-20261007','nprach-calibration.mat')),...
    string(fullfile(root,'verification','completion','stage-2','calibration-r2025b-20261007.stdout.log')),...
    string(beforeRegistryPath),string(afterRegistryPath),...
    string(fullfile(root,'verification','completion','stage-2','validateStage2RevalidationProvenance.m')),...
    string(notePath)];
extraEvidence=[string(rawRunReport),string(manifestPath),string(temporaryRegistry),...
    string(beforeRegistryPath),string(afterRegistryPath),...
    string(fullfile(root,'verification','completion','stage-2','runStage2Revalidation.m'))];
evidenceFiles=[evidenceFiles extraEvidence];
for k=1:numel(evidenceFiles)
    assert(isfile(evidenceFiles(k)),'nbiot:stage2:Recovery','Recovery evidence file is missing.');
end
evidenceHashes=struct('relativePath',{},'sha256',{});
for k=1:numel(evidenceFiles)
    relative=relativeToRoot(root,char(evidenceFiles(k)));
    evidenceHashes(end+1)=struct('relativePath',relative,...
        'sha256',fileHash(char(evidenceFiles(k)))); %#ok<AGROW>
end
manifestRows=string({evidenceHashes.relativePath})+" "+string({evidenceHashes.sha256});
evidenceManifestSha256=hashText(strjoin(manifestRows,newline));

base=nbiot.experiments.loadCalibration(nbiot.config.defaultConfig(),calibrationPath);
base=rmfield(base,'calibrationReport');
report=struct('conditions',conditions,'options',savedRun.report.options,...
    'successDefinition','Decoded RAR, accepted CRC/protocol Msg3, matching CRC/protocol Msg4',...
    'scope','10-ID diagnostics do not replace Stage 7 or 100-realization comparisons.',...
    'calibrationSha256',savedRun.report.calibrationSha256,...
    'threshold',base.phy.nprachThreshold,...
    'receiverRevision',savedRun.report.receiverRevision,...
    'sourceManifest',savedRun.report.sourceManifest,'matlabVersion',savedRun.report.matlabVersion,...
    'matlabRelease',savedRun.report.matlabRelease,'lteVersion',savedRun.report.lteVersion,...
    'artifactSourceHashes',savedRun.report.artifactSourceHashes,'trials',trials,...
    'summary',cell2table(summaries,'VariableNames',{'conditionId','condition','event',...
        'independentIds','eventCount','probability','lo95','hi95'}),...
    'independentIds',{idLists},'receiverChecks',receiver.checks,...
    'interferenceReplay',replayReport.interferenceReplay,...
    'realizationAssignments',struct('collisionDiagnostics',collisionIds,...
        'receiverDiagnostics',receiverIds,'interferenceReplay',3300),...
    'elapsedSeconds',savedRun.report.elapsedSeconds,'revalidation',revalidation,...
    'recovery',struct('mode','paired-rerun-after-cfo-detector-fix',...
        'receiverAssignmentMode','new-completed-assignment',...
        'sourcePhysicalRun',relativeToRoot(root,sourceFolder),...
        'correctedReplayRun',relativeToRoot(root,replayFolder),...
        'evidenceManifestSha256',evidenceManifestSha256,'evidenceHashes',evidenceHashes,...
        'reason',recoveryNote));

nbiot.experiments.reconcileFailedRealizationUse(officialRegistry,...
    'stage-2-collision-diagnostics',collisionIds,relativeToRoot(root,sourceFolder),...
    evidenceManifestSha256,recoveryNote);
report.registrySha256=fileHash(officialRegistry);
save(fullfile(sourceFolder,'report.mat'),'report','-v7');
save(fullfile(sourceFolder,'stage2-report.mat'),'report','-v7');
writetable(report.trials,fullfile(sourceFolder,'trials.csv'));
writetable(report.summary,fullfile(sourceFolder,'summary.csv'));
fprintf('STAGE2_RECOVERED trials=%d receiverChecks=%d evidenceFiles=%d elapsedSeconds=%.3f\n',...
    height(report.trials),height(report.receiverChecks),numel(evidenceHashes),report.elapsedSeconds);
end

function verifyReplay(replay)
if height(replay)~=8||~isequal(unique(replay.deltaDb).',[0 40])
    error('nbiot:stage2:Recovery','Corrected replay must contain both power conditions.');
end
for delta=[0 40]
    required=["full-noisy";"full-clean";"desired-noisy";"desired-clean"];
    actual=sort(string(replay.variant(replay.deltaDb==delta)));
    if ~isequal(actual,sort(required))
        error('nbiot:stage2:Recovery','Replay variants are incomplete at %d dB.',delta);
    end
end
equalFull=replay(replay.deltaDb==0&strcmp(replay.variant,'full-noisy'),:);
equalDesired=replay(replay.deltaDb==0&strcmp(replay.variant,'desired-noisy'),:);
nearFull=replay(replay.deltaDb==40&strcmp(replay.variant,'full-noisy'),:);
nearDesired=replay(replay.deltaDb==40&strcmp(replay.variant,'desired-noisy'),:);
if equalFull.crcError||~equalFull.payloadMatchesActualTx||...
        equalDesired.crcError||~equalDesired.payloadMatchesActualTx||...
        ~nearFull.crcError||nearDesired.crcError||~nearDesired.payloadMatchesActualTx
    error('nbiot:stage2:Recovery','Equal-power or near-far replay did not reproduce its expected physical outcome.');
end
end

function interval=binomialInterval(k,n)
if k==0, lo=0; else, lo=betaincinv(.025,k,n-k+1); end
if k==n, hi=1; else, hi=betaincinv(.975,k+1,n-k); end
interval=[lo hi];
end

function path=resolveFolder(root,path)
root=canonicalPath(root);
path=char(string(path));
if ~isfolder(path), path=fullfile(root,path); end
assert(isfolder(path),'nbiot:stage2:Recovery','Evidence folder does not exist.');
path=canonicalPath(path);
assert(isInsideRoot(root,path),'nbiot:stage2:Recovery',...
    'Recovery folders must remain inside the project root.');
end

function relative=relativeToRoot(root,path)
root=canonicalPath(root); path=canonicalPath(path); prefix=[root filesep];
if ~isInsideRoot(root,path)
    error('nbiot:stage2:Recovery','Evidence paths must remain inside the project root.');
end
relative=strrep(path(numel(prefix)+1:end),filesep,'/');
end

function path=canonicalPath(path)
path=char(java.io.File(path).getCanonicalPath());
end

function path=resolveEvidencePath(root,relative)
root=canonicalPath(root);
path=canonicalPath(fullfile(root,strrep(char(relative),'/',filesep)));
if ~isInsideRoot(root,path)
    error('nbiot:stage2:Recovery','Evidence metadata paths must remain inside the project root.');
end
end

function inside=isInsideRoot(root,path)
prefix=[root filesep];
inside=startsWith(lower(path),lower(prefix));
end

function requireRegistryAssignment(registry,role,ids,status)
matches=0; found=false; ids=sort(double(ids(:).'));
for k=1:numel(registry.assignments)
    assignment=registry.assignments(k);
    if strcmp(assignment.role,role)&&isequal(sort(double(assignment.ids(:).')),ids)
        matches=matches+1;
        found=found||strcmp(assignment.status,status);
    end
end
if matches~=1||~found
    error('nbiot:stage2:Recovery',...
        'Registry must contain one exact %s assignment for role %s.',status,role);
end
end

function hex=fileHash(path)
fid=fopen(path,'rb');
assert(fid>=0,'nbiot:stage2:Recovery','Cannot read evidence file %s.',path);
cleanup=onCleanup(@() fclose(fid));
digest=java.security.MessageDigest.getInstance('SHA-256');
while true
    bytes=fread(fid,4*1024*1024,'*uint8'); if isempty(bytes), break; end
    digest.update(typecast(bytes(:),'int8'));
end
hex=lower(reshape(dec2hex(typecast(digest.digest(),'uint8'),2).',1,[]));
end

function hex=hashText(value)
digest=java.security.MessageDigest.getInstance('SHA-256');
bytes=unicode2native(char(value),'UTF-8'); digest.update(typecast(bytes(:),'int8'));
hex=lower(reshape(dec2hex(typecast(digest.digest(),'uint8'),2).',1,[]));
end
